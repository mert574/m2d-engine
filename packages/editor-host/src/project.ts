/**
 * A project on disk: the folder the editor and an agent both work in.
 *
 * The browser reaches a project through the File System Access API; the
 * companion reaches the same folder through `node:fs`. This is the Node
 * half, and it is deliberately the smaller idea — a folder with scenes in
 * it and an asset manifest beside them. What a project *is* grows with
 * E5 (templates, build settings); until something needs more, it is this.
 */

import { readFile, writeFile, readdir, stat } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';
import { SceneDocument } from 'm2d-editor-core';

/** A scene file found in a project. */
export interface SceneEntry {
  /** Project-relative, with forward slashes: `src/yard/scenes/yard.json`. */
  path: string;
  name: string | null;
  type: string | null;
  generator: string | null;
}

/** One game a project declares in `m2d.project.json`. */
export interface GameEntry {
  name: string;
  /** The game-definition module, project-relative: exports `register(game)` and may export `GAME` options. */
  definition: string;
  /** The folder its scene JSON lives in, project-relative. */
  scenes: string;
  /** What asset URLs in its scenes are relative to, project-relative. */
  basePath: string;
}

export interface ProjectConfig {
  name: string;
  games: GameEntry[];
}

export class Project {
  readonly root: string;

  constructor(root: string) {
    this.root = resolve(root);
  }

  /**
   * Resolve a project-relative path, refusing to leave the project. An
   * agent names paths, so this is the boundary that keeps a tool call
   * from reading `../../.ssh/id_rsa`.
   */
  resolve(path: string): string {
    const full = resolve(this.root, path);
    if (full !== this.root && !full.startsWith(this.root + sep)) {
      throw new Error(`Project: '${path}' is outside the project`);
    }
    return full;
  }

  /**
   * The project's declaration, `m2d.project.json` at its root: its name
   * and its games — which module registers each game's classes, where its
   * scenes live, what its asset paths are relative to. A folder without
   * one still opens; its scenes just have no game to run them with.
   */
  async config(): Promise<ProjectConfig> {
    const fallback = { name: this.root.split(sep).pop() ?? 'project', games: [] };
    try {
      const raw = JSON.parse(await readFile(join(this.root, 'm2d.project.json'), 'utf8')) as Partial<ProjectConfig>;
      const games = (Array.isArray(raw.games) ? raw.games : []).filter((game): game is GameEntry =>
        typeof game?.name === 'string' && typeof game?.definition === 'string'
        && typeof game?.scenes === 'string' && typeof game?.basePath === 'string');
      return { name: typeof raw.name === 'string' ? raw.name : fallback.name, games };
    } catch {
      return fallback;
    }
  }

  /** Every `.json` scene under the project, by walking it. */
  async scenes(): Promise<SceneEntry[]> {
    const found: SceneEntry[] = [];
    const walk = async (dir: string): Promise<void> => {
      let entries;
      try {
        entries = await readdir(dir, { withFileTypes: true });
      } catch {
        return;
      }
      for (const entry of entries) {
        if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
        const full = join(dir, entry.name);
        if (entry.isDirectory()) {
          await walk(full);
          continue;
        }
        if (!entry.name.endsWith('.json')) continue;
        const doc = await this.#read(full);
        // A scene is a document with a version and a scene type; the
        // project's package.json and its tsconfig are not scenes.
        if (doc?.type !== 'level' && doc?.type !== 'ui') continue;
        found.push({
          path: relative(this.root, full).split(sep).join('/'),
          name: doc.name,
          type: doc.type,
          generator: doc.generator
        });
      }
    };
    await walk(this.root);
    found.sort((a, b) => a.path.localeCompare(b.path));
    return found;
  }

  /** Open one scene as a document. */
  async openScene(path: string): Promise<SceneDocument> {
    const full = this.resolve(path);
    return SceneDocument.parse(await readFile(full, 'utf8'), path);
  }

  /**
   * Write a document back in canonical form. Refuses a generated scene:
   * the next run of its script would overwrite this, so saving one is
   * not a save but a loss waiting to happen. Detach it first by deleting
   * its `generator`.
   */
  async saveScene(doc: SceneDocument): Promise<void> {
    if (!doc.path) throw new Error('Project: the document has no path to save to');
    if (doc.generator) {
      throw new Error(
        `Project: '${doc.path}' is generated by ${doc.generator} and is read-only; ` +
        "edit that script, or delete the scene's 'generator' field to detach it");
    }
    await writeFile(this.resolve(doc.path), doc.text);
    doc.markSaved();
  }

  /** Whether the project folder is there at all. */
  async exists(): Promise<boolean> {
    try {
      return (await stat(this.root)).isDirectory();
    } catch {
      return false;
    }
  }

  async #read(full: string): Promise<{ type: string | null; name: string | null; generator: string | null } | null> {
    try {
      const data = JSON.parse(await readFile(full, 'utf8')) as Record<string, unknown>;
      return {
        type: typeof data.type === 'string' ? data.type : null,
        name: typeof data.name === 'string' ? data.name : null,
        generator: typeof data.generator === 'string' ? data.generator : null
      };
    } catch {
      return null;
    }
  }
}
