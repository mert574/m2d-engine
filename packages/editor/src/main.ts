/**
 * The editor app's entry point.
 *
 * Served by `m2d-editor <project>` (packages/editor-host), which pins one
 * project at boot. E1+: the project's scenes in the tree panel, the
 * chosen one materialized in the viewport with the game's *real* classes
 * — imported from the host — and any node's fields in the inspector.
 *
 * Hot reload: when a source file changes, Vite invalidates its module
 * graph, the definition is re-imported fresh, and the scene
 * re-materializes from the in-memory document (never the file: there may
 * be unsaved edits) with the camera held still. When a scene file
 * changes on disk — a hand edit, a generator rerun, an agent over MCP —
 * the open document reloads unless it has unsaved edits of its own.
 */

import { sceneOutline, inspectNode, SceneDocument, type OutlineNode } from 'm2d-editor-core';
import {
  loadProject, readSceneText, gameFor, assetBase, loadDefinition, onProjectFile,
  type HostProject, type SceneEntry, type GameDefinition
} from './host.ts';
import { Viewport } from './viewport.ts';
import { createTree } from './tree.ts';
import { createInspector } from './inspector.ts';

const status = document.getElementById('status') as HTMLElement;
const plate = document.getElementById('plate') as HTMLElement;
const treePanel = document.querySelector('[data-region="tree"]') as HTMLElement;
const inspectorPanel = document.querySelector('[data-region="inspector"]') as HTMLElement;
const viewport = new Viewport(document.getElementById('screen') as HTMLCanvasElement);
const inspector = createInspector(inspectorPanel);

let project: HostProject | null = null;
let current: SceneDocument | null = null;
let currentEntry: SceneEntry | null = null;
let definition: GameDefinition | null = null;
/** Bumped per code change; makes the next definition import fresh. */
let generation = 0;

const tree = createTree(treePanel, (node: OutlineNode) => {
  if (!current) return;
  const title = node.path.length ? `${node.label}${node.detail ? ` · ${node.detail}` : ''}` : current.name ?? 'Scene';
  inspector.show(title, inspectNode(current.data, node.path));
});

function say(text: string): void {
  status.textContent = text;
}

function showPlate(text: string | null): void {
  plate.textContent = text ?? '';
  plate.classList.toggle('gone', text === null);
}

/** The scene list, grouped by game, shown until a scene is open. */
function listScenes(): void {
  if (!project) return;
  treePanel.replaceChildren();
  const heading = document.createElement('h2');
  heading.textContent = 'Scenes';
  treePanel.append(heading);

  const groups = new Map<string, SceneEntry[]>();
  for (const entry of project.scenes) {
    const game = gameFor(project, entry.path);
    const key = game?.name ?? 'Other scenes';
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key)!.push(entry);
  }
  for (const [label, entries] of groups) {
    const group = document.createElement('div');
    group.className = 'scene-group';
    group.textContent = label;
    treePanel.append(group);
    for (const entry of entries) {
      const button = document.createElement('button');
      button.type = 'button';
      button.className = 'scene';
      button.textContent = entry.name ?? entry.path;
      button.title = entry.generator
        ? `${entry.path} — generated by ${entry.generator}, read-only`
        : entry.path;
      if (entry.generator) button.dataset.generated = 'true';
      button.addEventListener('click', () => { void open(entry); });
      treePanel.append(button);
    }
  }
  if (!project.scenes.length) {
    const empty = document.createElement('div');
    empty.className = 'empty';
    empty.textContent = 'No scenes in this project.';
    treePanel.append(empty);
  }
}

/** Materialize the current document with the current definition. */
async function materialize(): Promise<void> {
  if (!project || !current) return;
  const game = currentEntry ? gameFor(project, currentEntry.path) : null;
  await viewport.show(current, {
    definition,
    basePath: assetBase(project, game),
    sceneNames: project.scenes.flatMap((scene) => (scene.name ? [scene.name] : []))
  });
}

async function open(entry: SceneEntry): Promise<void> {
  if (!project) return;
  showPlate(`Opening ${entry.path}…`);
  try {
    const doc = SceneDocument.parse(await readSceneText(entry.path), entry.path);
    const problems = doc.validate();
    if (!problems.ok) {
      const first = problems.issues[0];
      showPlate(`${entry.path} does not validate — ${first?.path || '(document)'}: ${first?.message}`);
      say(`${entry.path}: invalid`);
      return;
    }
    const game = gameFor(project, entry.path);
    definition = game ? await loadDefinition(project, game, generation) : null;
    current = doc;
    currentEntry = entry;
    tree.show(sceneOutline(doc.data));
    inspector.show(doc.name ?? 'Scene', inspectNode(doc.data, []));
    await materialize();
    showPlate(null);
    say(`${entry.path}${doc.generator ? ' (generated, read-only)' : ''}${game ? '' : ' — no game declares this scene; placeholders only'}`);
  } catch (error) {
    viewport.close();
    showPlate(String((error as Error).message ?? error));
    say(`${entry.path}: could not open`);
  }
}

/** A source file changed: fresh classes, same document, same camera. */
async function reloadCode(): Promise<void> {
  if (!project || !current || !currentEntry) return;
  const game = gameFor(project, currentEntry.path);
  if (!game) return;
  generation = Date.now();
  try {
    definition = await loadDefinition(project, game, generation);
    const camera = viewport.captureCamera();
    await materialize();
    viewport.restoreCamera(camera);
    say(`${currentEntry.path} — code reloaded`);
  } catch (error) {
    showPlate(`Hot reload failed: ${String((error as Error).message ?? error)}`);
  }
}

/** A scene file changed on disk: reload it unless this editor has edits. */
async function reloadScene(path: string): Promise<void> {
  if (!project) return;
  const entry = project.scenes.find((scene) => scene.path === path);
  if (currentEntry && path === currentEntry.path) {
    if (current?.dirty) {
      say(`${path} changed on disk — keeping your unsaved edits`);
      return;
    }
    await open(currentEntry);
    return;
  }
  // A scene appeared or went away: refresh the listing next time it shows.
  if (!entry) project = await loadProject();
}

onProjectFile((path) => {
  if (path.endsWith('.json')) void reloadScene(path);
  else if (/\.(js|ts|mjs)$/.test(path)) void reloadCode();
});

try {
  project = await loadProject();
  say(project.name);
  showPlate('Pick a scene.');
  listScenes();
} catch (error) {
  showPlate(String((error as Error).message ?? error));
}
