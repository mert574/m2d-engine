/**
 * The editor app's entry point.
 *
 * E1, the read-only viewer: open a project (or `?demo` for a built-in
 * scene), pick a scene, see its outline in the tree, its world in the
 * viewport, and any selected node's fields in the inspector — every
 * field the schema declares, set or not, with what absence means. The
 * inspector writing back is E2.
 */

import { sceneOutline, inspectNode, SceneDocument, type OutlineNode } from 'm2d-editor-core';
import { BrowserProject, canOpenProjects, type SceneEntry } from './project.ts';
import { withProjectAssets } from './assetUrls.ts';
import { Viewport } from './viewport.ts';
import { createTree } from './tree.ts';
import { createInspector } from './inspector.ts';
import { demoScene } from './demoScene.ts';

const openButton = document.getElementById('open') as HTMLButtonElement;
const status = document.getElementById('status') as HTMLElement;
const plate = document.getElementById('plate') as HTMLElement;
const treePanel = document.querySelector('[data-region="tree"]') as HTMLElement;
const inspectorPanel = document.querySelector('[data-region="inspector"]') as HTMLElement;
const viewport = new Viewport(document.getElementById('screen') as HTMLCanvasElement);
const inspector = createInspector(inspectorPanel);

let project: BrowserProject | null = null;
let current: SceneDocument | null = null;

const tree = createTree(treePanel, (node: OutlineNode) => {
  if (!current) return;
  const title = node.path.length ? `${node.label}${node.detail ? ` · ${node.detail}` : ''}` : current.name ?? 'Scene';
  inspector.show(title, inspectNode(current.data, node.path));
});

function say(text: string): void {
  status.textContent = text;
}

function showPlate(text: string | null): void {
  plate.textContent = text ?? '';
  plate.classList.toggle('gone', text === null);
}

/** A document into all three panels. */
async function showDocument(doc: SceneDocument, sceneNames: string[] = []): Promise<void> {
  current = doc;
  tree.show(sceneOutline(doc.data));
  inspector.show(doc.name ?? 'Scene', inspectNode(doc.data, []));
  // The viewport draws a copy whose asset URLs reach into the project
  // folder; the document itself stays what the file says.
  const prepared = project && doc.path ? await withProjectAssets(doc.data, project, doc.path) : null;
  await viewport.show(doc, {
    sceneNames,
    ...(prepared && { data: prepared.data, cleanup: () => prepared.revoke() })
  });
  showPlate(null);
}

/** The project's scene files, listed in the tree panel until one is open. */
function listScenes(scenes: SceneEntry[]): void {
  treePanel.replaceChildren();
  const heading = document.createElement('h2');
  heading.textContent = 'Scenes';
  treePanel.append(heading);

  if (!scenes.length) {
    const empty = document.createElement('div');
    empty.className = 'empty';
    empty.textContent = 'No scenes in this folder.';
    treePanel.append(empty);
    return;
  }

  for (const entry of scenes) {
    const button = document.createElement('button');
    button.type = 'button';
    button.className = 'scene';
    button.textContent = entry.name ?? entry.path;
    button.title = entry.generator
      ? `${entry.path} — generated by ${entry.generator}, read-only`
      : entry.path;
    if (entry.generator) button.dataset.generated = 'true';
    button.addEventListener('click', () => { void open(entry, scenes); });
    treePanel.append(button);
  }
}

async function open(entry: SceneEntry, all: SceneEntry[]): Promise<void> {
  if (!project) return;
  showPlate(`Opening ${entry.path}…`);
  try {
    const doc = await project.openScene(entry);
    const problems = doc.validate();
    if (!problems.ok) {
      const first = problems.issues[0];
      showPlate(`${entry.path} does not validate — ${first?.path || '(document)'}: ${first?.message}`);
      say(`${entry.path}: invalid`);
      return;
    }
    await showDocument(doc, all.flatMap((other) => (other.name ? [other.name] : [])));
    say(`${entry.path}${doc.generator ? ' (generated, read-only)' : ''}`);
  } catch (error) {
    viewport.close();
    showPlate(String((error as Error).message ?? error));
    say(`${entry.path}: could not open`);
  }
}

openButton.addEventListener('click', async () => {
  try {
    project = await BrowserProject.open();
  } catch (error) {
    // An abort is the user changing their mind, not a failure.
    if ((error as Error).name !== 'AbortError') showPlate(String((error as Error).message ?? error));
    return;
  }
  say(project.name);
  showPlate('Pick a scene.');
  listScenes(await project.scenes());
});

if (!canOpenProjects()) {
  openButton.disabled = true;
  showPlate('The editor needs the File System Access API to open a project: Chrome or Edge.');
}

// `?demo`: a built-in scene with no folder to pick — the editor's own
// smoke test, and the quickest way to see the panels working.
if (new URLSearchParams(location.search).has('demo')) {
  say('demo scene');
  void showDocument(new SceneDocument(demoScene())).catch((error) => {
    showPlate(String((error as Error).message ?? error));
  });
}
