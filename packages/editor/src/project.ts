/**
 * A project in the browser: a folder the user granted through the File
 * System Access API.
 *
 * The Node companion has the same idea in `m2d-editor-mcp`'s `Project`,
 * over `node:fs`. They are deliberately separate: the two runtimes reach
 * files in genuinely different ways, and one abstraction over both would
 * be a lowest common denominator neither wants. What they share is
 * `editor-core` — the document, the commands and the writer — which is
 * the half that actually matters.
 *
 * Chromium only, as the 3D renderer already is.
 */

import { SceneDocument } from 'm2d-editor-core';

/** A scene file found in a project. */
export interface SceneEntry {
  path: string;
  name: string | null;
  type: string | null;
  generator: string | null;
  handle: FileSystemFileHandle;
}

/** Whether this browser can open a project folder at all. */
export function canOpenProjects(): boolean {
  return typeof window !== 'undefined' && 'showDirectoryPicker' in window;
}

export class BrowserProject {
  readonly root: FileSystemDirectoryHandle;
  readonly name: string;

  constructor(root: FileSystemDirectoryHandle) {
    this.root = root;
    this.name = root.name;
  }

  /** Ask the user for a folder. Rejects if they cancel. */
  static async open(): Promise<BrowserProject> {
    if (!canOpenProjects()) {
      throw new Error('This browser cannot open a project folder: the editor needs the File System Access API (Chrome or Edge).');
    }
    const handle = await window.showDirectoryPicker({ id: 'm2d-project', mode: 'readwrite' });
    return new BrowserProject(handle);
  }

  /** Every scene in the project, by walking it. */
  async scenes(): Promise<SceneEntry[]> {
    const found: SceneEntry[] = [];
    const walk = async (dir: FileSystemDirectoryHandle, prefix: string): Promise<void> => {
      for await (const [name, handle] of dir.entries()) {
        if (name.startsWith('.') || name === 'node_modules') continue;
        const path = prefix ? `${prefix}/${name}` : name;
        if (handle.kind === 'directory') {
          await walk(handle as FileSystemDirectoryHandle, path);
          continue;
        }
        if (!name.endsWith('.json')) continue;
        const entry = await this.#describe(handle as FileSystemFileHandle, path);
        if (entry) found.push(entry);
      }
    };
    await walk(this.root, '');
    found.sort((a, b) => a.path.localeCompare(b.path));
    return found;
  }

  /** Open one scene as a document. */
  async openScene(entry: SceneEntry): Promise<SceneDocument> {
    const file = await entry.handle.getFile();
    return SceneDocument.parse(await file.text(), entry.path);
  }

  /** Write a document back in canonical form, refusing a generated scene. */
  async saveScene(doc: SceneDocument, entry: SceneEntry): Promise<void> {
    if (doc.generator) {
      throw new Error(
        `'${doc.path}' is generated by ${doc.generator} and is read-only; ` +
        "edit that script, or delete the scene's 'generator' field to detach it");
    }
    const writable = await entry.handle.createWritable();
    await writable.write(doc.text);
    await writable.close();
    doc.markSaved();
  }

  /** A file by project-relative path, or null when nothing is there. */
  async readFile(path: string): Promise<File | null> {
    const parts = path.split('/').filter(Boolean);
    const name = parts.pop();
    if (!name) return null;
    let dir: FileSystemDirectoryHandle = this.root;
    try {
      for (const part of parts) dir = await dir.getDirectoryHandle(part);
      return await (await dir.getFileHandle(name)).getFile();
    } catch {
      return null;
    }
  }

  async #describe(handle: FileSystemFileHandle, path: string): Promise<SceneEntry | null> {
    try {
      const data = JSON.parse(await (await handle.getFile()).text()) as Record<string, unknown>;
      if (data.type !== 'level' && data.type !== 'ui') return null;
      return {
        path,
        name: typeof data.name === 'string' ? data.name : null,
        type: data.type,
        generator: typeof data.generator === 'string' ? data.generator : null,
        handle
      };
    } catch {
      return null;
    }
  }
}
